// Copies shared/types.ts into src/shared/ so the chaincode package is self-contained.
// Fabric builds chaincode with plain `npm install` inside a container that only
// sees this folder, so a pnpm workspace link to @wrt/shared would not resolve.
const fs = require('fs');
const path = require('path');

const src = path.resolve(__dirname, '../../../shared/types.ts');
const destDir = path.resolve(__dirname, '../src/shared');
const header = '// GENERATED by scripts/sync-shared.js from shared/types.ts. Do not edit.\n\n';

fs.mkdirSync(destDir, { recursive: true });
fs.writeFileSync(path.join(destDir, 'types.ts'), header + fs.readFileSync(src, 'utf8'));
